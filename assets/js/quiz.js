// ================= REALTIME LEADERBOARD V5 - FIREBASE/FALLBACK =================
let kvhFirebaseDb = null;
let kvhLeaderboardUnsubscribe = null;
let kvhLiveLeaderboardRows = [];

function kvhCanUseFirebase(){
  return Boolean(
    typeof KVH_FIREBASE_ENABLED !== 'undefined' &&
    KVH_FIREBASE_ENABLED &&
    typeof firebase !== 'undefined' &&
    typeof firebase.initializeApp === 'function' &&
    typeof firebase.firestore === 'function'
  );
}

function initFirebaseLeaderboard(){
  if(!kvhCanUseFirebase()) {
    renderLeaderboard();
    return;
  }
  try{
    if(!firebase.apps.length){
      firebase.initializeApp(firebaseConfig);
    }
    kvhFirebaseDb = firebase.firestore();

    if(kvhLeaderboardUnsubscribe) kvhLeaderboardUnsubscribe();

    kvhLeaderboardUnsubscribe = kvhFirebaseDb
      .collection(KVH_FIREBASE_COLLECTION || 'huit_hcm_quiz_leaderboard')
      .orderBy('score', 'desc')
      .orderBy('duration', 'asc')
      .limit(50)
      .onSnapshot((snapshot) => {
        kvhLiveLeaderboardRows = snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() }));
        renderLeaderboard();
      }, (error) => {
        console.warn('Firebase leaderboard error:', error);
        renderLeaderboard();
      });
  }catch(error){
    console.warn('Không khởi tạo được Firebase, dùng localStorage:', error);
    renderLeaderboard();
  }
}

const __kvhLocalGetLeaderboard = getLeaderboard;
getLeaderboard = function(){
  if(kvhFirebaseDb && kvhLiveLeaderboardRows.length){
    return kvhLiveLeaderboardRows;
  }
  try { return JSON.parse(localStorage.getItem(LEADERBOARD_KEY) || '[]'); }
  catch(e) { return []; }
};

const __kvhLocalSaveLeaderboard = saveLeaderboard;
saveLeaderboard = async function(rowsOrRow){
  // rowsOrRow có thể là 1 object bài thi mới hoặc mảng fallback
  const isSingleRow = rowsOrRow && !Array.isArray(rowsOrRow) && typeof rowsOrRow === 'object';

  if(kvhFirebaseDb && isSingleRow){
    const row = {
      ...rowsOrRow,
      createdAt: firebase.firestore.FieldValue.serverTimestamp(),
      clientTime: new Date().toISOString()
    };
    await kvhFirebaseDb.collection(KVH_FIREBASE_COLLECTION || 'huit_hcm_quiz_leaderboard').add(row);
    return;
  }

  if(kvhFirebaseDb && Array.isArray(rowsOrRow)){
    // Không ghi cả mảng lên Firebase để tránh trùng dữ liệu.
    return;
  }

  const rows = Array.isArray(rowsOrRow) ? rowsOrRow : [rowsOrRow];
  localStorage.setItem(LEADERBOARD_KEY, JSON.stringify(rows));
  if(typeof kvhBroadcastNow === 'function') kvhBroadcastNow();
};

