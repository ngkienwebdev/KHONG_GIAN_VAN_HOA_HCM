function shuffleArray(arr){ return [...arr].sort(() => Math.random() - 0.5); }
function pickQuizQuestions(){ return shuffleArray(QUIZ_BANK).slice(0, Math.min(QUIZ_SIZE, QUIZ_BANK.length)); }
